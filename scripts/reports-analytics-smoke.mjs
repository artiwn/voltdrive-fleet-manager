import assert from 'node:assert/strict';
import fs from 'node:fs';
class MemoryStorage{constructor(){this.map=new Map()}getItem(k){return this.map.has(k)?this.map.get(k):null}setItem(k,v){this.map.set(k,String(v))}removeItem(k){this.map.delete(k)}clear(){this.map.clear()}}
globalThis.localStorage=new MemoryStorage();
const api=await import('../js/core/fleet-state.js?reports='+Date.now());
const reporting=await import('../js/core/reporting.js?reports='+Date.now());
api.setCurrentAccessUserId('USR-01');
const state=api.loadState();
const week=reporting.buildFleetReport(state,{period:'week',departmentId:'all',vehicleId:'all',driverId:'all',chargerId:'all'});
const month=reporting.buildFleetReport(state,{period:'month',departmentId:'all',vehicleId:'all',driverId:'all',chargerId:'all'});
const quarter=reporting.buildFleetReport(state,{period:'quarter',departmentId:'all',vehicleId:'all',driverId:'all',chargerId:'all'});
assert.ok(week.sessions.length>7,'week must include dated historical sessions beyond the current live records');
assert.ok(month.sessions.length>=week.sessions.length,'30-day period must contain at least the 7-day records');
assert.ok(quarter.sessions.length>=month.sessions.length,'90-day period must contain at least the 30-day records');
assert.ok(quarter.energy>month.energy&&month.energy>week.energy,'period energy must grow from actual additional records, not scaling');
assert.ok(week.parkingUsage.length>0&&week.bayUtilization>0&&week.bayUtilization<=100,'parking-bay utilization must come from dated bay records');
assert.ok(month.reservationCounts.total>0,'reservation analytics must have dated records');
assert.ok(quarter.reservationCounts.noShow>0,'reservation analytics must include no-show outcomes');
assert.ok(quarter.maintenance.length>0&&quarter.resolvedMaintenance.length>0,'maintenance performance must use ticket history');
assert.ok(quarter.energyHistory.length>0&&quarter.renewableKwh>0&&quarter.carbonAvoidedKg>0,'renewable/carbon analytics must use dated energy records');
assert.ok(week.trend.length===7,'7-day trend must use seven dated buckets');
assert.ok(week.trend.some(x=>x.sessions>0),'trend must contain actual session buckets');
const sumSessions=week.sessions.reduce((a,x)=>a+(Number(x.energy)||0),0);const sumHome=week.reimbursements.reduce((a,x)=>a+(Number(x.energy)||0),0);
assert.equal(Number(week.energy.toFixed(3)),Number((sumSessions+sumHome).toFixed(3)),'report energy must equal the exact records in range');
api.setCurrentAccessUserId('USR-02');
const central=api.loadState();
assert.ok((central.energyHistory||[]).every(x=>x.depotId==='DEPOT-YER-CENTRAL'),'scoped report history must honor depot access');
assert.ok((central.maintenanceTickets||[]).every(x=>x.depotId==='DEPOT-YER-CENTRAL'),'maintenance history must honor depot access');
const source=fs.readFileSync(new URL('../js/pages/reports.js',import.meta.url),'utf8');
assert.doesNotMatch(source,/factor\s*:/,'Reports page must not use period scaling factors');
assert.match(source,/report-bay-utilization/,'Reports page must render parking-bay utilization');
assert.match(source,/report-maintenance-summary/,'Reports page must render maintenance performance');
assert.match(source,/report-renewable/,'Reports page must render renewable/carbon analytics');
console.log('OK: Fleet Reports & Analytics smoke test passed.');
console.log(`Dated records: week ${week.sessions.length} sessions · month ${month.sessions.length} · quarter ${quarter.sessions.length}`);
console.log(`Quarter: ${quarter.reservationCounts.noShow} no-show reservations · ${quarter.maintenance.length} maintenance tickets · ${quarter.renewableKwh.toFixed(1)} kWh renewable`);
